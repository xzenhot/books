#!/usr/bin/env python3
"""Python equivalent of the `workshop expand` verb.

Expands the backlog book plan `workspaces/backlog/<bookname>/book.json` by running
the four workshop dimensions on each selected chapter, in order:

    1. summary    — expand chapter_summary into a longer, richer seed
    2. character  — add/extend per-chapter characters and the plan's all_characters
    3. reference  — refresh further_references with real internet sources
    4. update     — fill the `qualities` attributes from expand.json

Summary, character, and qualities content is generated by the local Ollama model,
grounded in the chapter's own summary/characters and the gist/storyline. References
are looked up through the shared search adapter (`.framework` search providers); when
a provider is unavailable or a lookup fails, references are left as-is rather than
fabricating a URL.

The plan is snapshotted before writing and replaced atomically, so a failure never
corrupts book.json.

Usage:
    python tools/expand.py <bookname> [n|range|list|all|*] [--verb summary|character|reference|update|expand]
    python tools/expand.py <bookname> all --verb expand --model gemma4:latest
"""

import argparse
import json
import os
import re
import secrets
import sys
import tempfile
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BACKLOG_ROOT = REPO_ROOT / "workspaces" / "backlog"
EXPAND_SCHEMA = (
    REPO_ROOT / ".framework" / "templates" / "backlog" / "v1" / "layout" / "expand.json"
)

MODEL = "gemma4:latest"
OLLAMA_URL = "http://127.0.0.1:11434/api/generate"
TIMEOUT = 900
CONTEXT_WINDOW = 64000
MAX_RETRIES = 3

NEWLINE = os.linesep
VERBOSE = False


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def vlog(*args):
    if VERBOSE:
        print("[v]", *args)


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(value, ensure_ascii=False, indent=4, allow_nan=False)
    data = (text.replace("\n", NEWLINE) + NEWLINE).encode("utf-8")
    tmp = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".expand-", suffix=".tmp", delete=False) as fh:
            tmp = Path(fh.name)
            fh.write(data)
        os.replace(tmp, path)
    finally:
        if tmp is not None and tmp.exists():
            tmp.unlink()


def run_ollama(prompt, system, temperature=0.5):
    """POST a prompt to the local Ollama instance and return the response text."""
    payload = {
        "model": MODEL,
        "system": system,
        "prompt": prompt,
        "stream": False,
        "think": False,
        "format": "json",
        "options": {
            "num_ctx": CONTEXT_WINDOW,
            "temperature": temperature,
            "top_p": 0.9,
            "seed": secrets.randbelow(2**31),
        },
    }
    encoded = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    last = None
    for attempt in range(1, MAX_RETRIES + 1):
        req = urllib.request.Request(
            OLLAMA_URL, data=encoded, headers={"Content-Type": "application/json"}
        )
        try:
            with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
                body = json.loads(resp.read().decode("utf-8"))
            if body.get("error"):
                raise ValueError(body["error"])
            return body.get("response", "")
        except (urllib.error.URLError, TimeoutError, ValueError) as e:
            last = e
            vlog(f"[ollama] attempt {attempt}/{MAX_RETRIES} failed: {e}")
            if attempt < MAX_RETRIES:
                time.sleep(5 * attempt)
    raise RuntimeError(f"Ollama request failed after {MAX_RETRIES} attempts: {last}")


def _extract_json(raw):
    """Parse a JSON object out of a model response (tolerates fences/trailing prose)."""
    cleaned = (raw or "").strip().lstrip("\ufeff")
    if cleaned.startswith("```"):
        lines = cleaned.splitlines()
        lines = lines[1:] if lines and lines[0].startswith("```") else lines
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        cleaned = "\n".join(lines).strip()
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        start = cleaned.find("{")
        if start < 0:
            raise ValueError("no JSON object in model response")
        depth = 0
        for i in range(start, len(cleaned)):
            c = cleaned[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    return json.loads(cleaned[start : i + 1])
    raise ValueError("unbalanced JSON object in model response")


# ---------------------------------------------------------------------------
# Chapter scope resolution
# ---------------------------------------------------------------------------

def parse_scope(value, chapters):
    """Resolve a scope token against a chapter list (ordered plan entries)."""
    by_name = {}
    by_index = {}
    for ch in chapters:
        by_name[str(ch.get("name"))] = ch
        idx = ch.get("chapter_index")
        if isinstance(idx, int):
            by_index[idx] = ch

    if value in {"all", "*"}:
        return chapters
    if "," in value:
        out = []
        seen = set()
        for token in value.split(","):
            for c in parse_scope(token.strip(), chapters):
                if id(c) not in seen:
                    seen.add(id(c))
                    out.append(c)
        return out
    m = re.fullmatch(r"(\d+)-(\d+)", value)
    if m:
        lo, hi = int(m.group(1)), int(m.group(2))
        return [c for c in chapters if lo <= c.get("chapter_index", -1) <= hi]
    if value in by_name:
        return [by_name[value]]
    if value.isdecimal() and int(value) in by_index:
        return [by_index[int(value)]]
    return []


# ---------------------------------------------------------------------------
# Expand schema
# ---------------------------------------------------------------------------

def load_quality_names():
    """Attribute names from expand.json's qualities object."""
    if not EXPAND_SCHEMA.is_file():
        return []
    data = read_json(EXPAND_SCHEMA)
    qualities = data.get("qualities")
    if isinstance(qualities, dict):
        return list(qualities.keys())
    return []


# ---------------------------------------------------------------------------
# Dimension prompts
# ---------------------------------------------------------------------------

SYSTEM = (
    "You enrich a chapter of a Bengali historical novel for a book plan. "
    "Return a single valid JSON object only — no Markdown fences, no commentary. "
    "Ground every value in the chapter summary, its characters, and the story gist "
    "you are given; never invent a new premise or a fabricated URL."
)


def summary_prompt(gist, chapter):
    return (
        "Expand this chapter's `chapter_summary` into a longer, more detailed seed "
        "(2–4 sentences, ~150–200 words) that names the central conflict, key imagery, "
        "and the open question it leaves. Keep it form-neutral and grounded in the gist. "
        "Return JSON: {\"chapter_summary\": \"...\"}.\n\n"
        f"GIST:\n{gist}\n\nCHAPTER:\n{json.dumps(chapter, ensure_ascii=False)}"
    )


def character_prompt(gist, chapter, roster_names):
    return (
        "Propose 3–5 characters for this chapter, each {id, name, role} (short Bengali). "
        "Derive from the chapter summary and the existing roster; do not invent a figure "
        "that contradicts the story. Return JSON: {\"characters\": [{\"id\":\"...\",\"name\":\"...\",\"role\":\"...\"}]}.\n\n"
        f"GIST:\n{gist}\n\nCHAPTER:\n{json.dumps(chapter, ensure_ascii=False)}\n\n"
        f"EXISTING CHARACTER NAMES:\n{roster_names}"
    )


def qualities_prompt(gist, chapter, quality_names, characters):
    return (
        "Fill each of these quality attributes for this chapter with a fresh, grounded "
        "sentence (Bengali) drawn from the chapter summary, its characters, and the gist. "
        "Do not reuse template sample text, and do not copy another chapter. "
        "Return JSON whose keys are exactly these attributes:\n"
        f"{json.dumps(quality_names, ensure_ascii=False)}\n\n"
        f"GIST:\n{gist}\n\nCHAPTER:\n{json.dumps(chapter, ensure_ascii=False)}\n\n"
        f"CHARACTERS:\n{json.dumps(characters, ensure_ascii=False)}"
    )


# ---------------------------------------------------------------------------
# Reference lookup (best-effort, no fabricated URLs)
# ---------------------------------------------------------------------------

def lookup_references(topics):
    """Search the web for a list of topics; return {topic: (title, url)} for hits."""
    try:
        sys.path.insert(0, str(REPO_ROOT / "tools"))
        from search.adapter import build_adapter
        adapter = build_adapter()
    except Exception as e:  # noqa: BLE001
        vlog(f"[reference] search adapter unavailable: {e}")
        return {}

    found = {}
    for topic in topics:
        try:
            results = adapter.search(
                provider_name=os.getenv("DEFAULT_SEARCH_PROVIDER", "searxng"),
                query=topic,
                max_results=1,
            )
            if results:
                r = results[0]
                found[topic] = (r.title, str(r.url))
        except Exception as e:  # noqa: BLE001
            vlog(f"[reference] lookup failed for '{topic}': {e}")
    return found


# ---------------------------------------------------------------------------
# Core expansion
# ---------------------------------------------------------------------------

def expand_chapter(gist, chapter, quality_names, verbs):
    """Run the requested dimensions on one chapter and return a merged dict."""
    result = dict(chapter)

    if "summary" in verbs:
        try:
            data = _extract_json(run_ollama(summary_prompt(gist, chapter), SYSTEM))
            if isinstance(data, dict) and data.get("chapter_summary"):
                result["chapter_summary"] = data["chapter_summary"]
                print(f"  [summary] {chapter.get('chapter_title')} — expanded")
        except Exception as e:  # noqa: BLE001
            print(f"  [summary] {chapter.get('chapter_title')} — skipped ({e})")

    if "character" in verbs:
        roster = [c.get("name", "") for c in chapter.get("characters", [])]
        try:
            data = _extract_json(run_ollama(character_prompt(gist, chapter, roster), SYSTEM))
            new = data.get("characters") if isinstance(data, dict) else None
            if isinstance(new, list) and new:
                existing = list(chapter.get("characters", []))
                existing.extend(c for c in new if isinstance(c, dict) and c.get("name"))
                result["characters"] = existing
                print(f"  [character] {chapter.get('chapter_title')} — +{len(new)} characters")
        except Exception as e:  # noqa: BLE001
            print(f"  [character] {chapter.get('chapter_title')} — skipped ({e})")

    if "reference" in verbs:
        topics = [r.get("reference", "") for r in chapter.get("further_references", [])]
        topics = [t for t in topics if t]
        found = lookup_references(topics)
        if found:
            refs = []
            for r in chapter.get("further_references", []):
                hit = found.get(r.get("reference", ""))
                refs.append({
                    "no": r.get("no", str(len(refs) + 1)),
                    "reference": r.get("reference", ""),
                    "weblink": hit[1] if hit else r.get("weblink", ""),
                })
            result["further_references"] = refs
            print(f"  [reference] {chapter.get('chapter_title')} — {len(found)} links found")
        else:
            print(f"  [reference] {chapter.get('chapter_title')} — no links (unchanged)")

    if "update" in verbs and quality_names:
        try:
            data = _extract_json(
                run_ollama(
                    qualities_prompt(gist, chapter, quality_names,
                                     chapter.get("characters", [])),
                    SYSTEM,
                )
            )
            if isinstance(data, dict) and data:
                result["qualities"] = data
                print(f"  [update] {chapter.get('chapter_title')} — {len(data)} qualities filled")
        except Exception as e:  # noqa: BLE001
            print(f"  [update] {chapter.get('chapter_title')} — skipped ({e})")

    return result


def main(argv=None):
    global VERBOSE, MODEL
    parser = argparse.ArgumentParser(description="Expand backlog chapters (workshop expand).")
    parser.add_argument("bookname", help="Book folder under workspaces/backlog/.")
    parser.add_argument("scope", nargs="?", default="all", help="n, range, list, all, or '*'.")
    parser.add_argument("--verb", default="expand",
                        help="summary|character|reference|update|expand (default: expand).")
    parser.add_argument("--model", default=None, help="Ollama model (default: from book.json, else gemma4:latest).")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    VERBOSE = args.verbose
    book_dir = BACKLOG_ROOT / args.bookname
    plan_file = book_dir / "book.json"
    if not plan_file.is_file():
        print(f"Error: no book.json at {plan_file}", file=sys.stderr)
        return 1

    plan = read_json(plan_file)
    chapters = plan.get("chapters", [])
    gist = plan.get("gist", "") or (book_dir / "gist.md").read_text(encoding="utf-8")
    quality_names = load_quality_names()

    verb = args.verb.strip().lower()
    if verb == "expand":
        verbs = ["summary", "character", "reference", "update"]
    elif verb in {"summary", "character", "reference", "update"}:
        verbs = [verb]
    else:
        print(f"Error: unknown verb '{verb}'", file=sys.stderr)
        return 1

    if args.model:
        MODEL = args.model

    selected = parse_scope(args.scope.strip().lower(), chapters)
    if not selected:
        print(f"Error: no chapters matched scope '{args.scope}'", file=sys.stderr)
        return 1

    print(f"Expanding '{args.bookname}' — verb {verb}, {len(selected)} chapter(s)")
    before = json.dumps(plan, ensure_ascii=False, sort_keys=True)
    for ch in selected:
        print(f"Chapter {ch.get('chapter_index')} — {ch.get('chapter_title')}")
        idx = ch.get("chapter_index")
        name = ch.get("name")
        for i, entry in enumerate(chapters):
            if entry.get("chapter_index") == idx and entry.get("name") == name:
                chapters[i] = expand_chapter(gist, ch, quality_names, verbs)
                break

    plan["chapters"] = chapters

    # Register any new characters into all_characters (dedupe by id).
    existing_ids = {c.get("id") for c in plan.get("all_characters", [])}
    for ch in chapters:
        for c in ch.get("characters", []):
            cid = c.get("id")
            if cid and cid not in existing_ids:
                plan.setdefault("all_characters", []).append(
                    {"id": cid, "name": c.get("name", ""), "role": c.get("role", ""),
                     "arc": ""}
                )
                existing_ids.add(cid)

    after = json.dumps(plan, ensure_ascii=False, sort_keys=True)
    if after == before:
        print("No changes; nothing written.")
        return 0

    # Snapshot before overwrite.
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    snap = book_dir / f"book.json.expand-{stamp}.bak"
    snap.write_bytes(plan_file.read_bytes())
    vlog(f"snapshot -> {snap}")

    write_json(plan_file, plan)
    print(f"Expanded plan written -> {plan_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
